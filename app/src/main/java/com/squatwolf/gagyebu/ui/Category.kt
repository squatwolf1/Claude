package com.squatwolf.gagyebu.ui

/** 분류마다 한눈에 알아보게 붙이는 그림 글자. */
fun emojiOf(category: String) = when (category) {
    "식비" -> "🍚"
    "카페" -> "☕"
    "교통" -> "🚌"
    "쇼핑" -> "🛍️"
    "생활" -> "🏠"
    "공과금" -> "🧾"
    "대출" -> "🏦"
    "유류" -> "⛽"
    "병원" -> "🏥"
    "의료" -> "💊"
    "문화" -> "🎬"
    "월급" -> "💰"
    "용돈" -> "🎁"
    "부수입" -> "💵"
    else -> "📌"
}
